const { _electron } = require('playwright-core');
// Run after `npm run build`; all data is isolated under this project's work folder.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const root = path.resolve('work', `notes-ui-${crypto.randomUUID()}`);
  await fs.mkdir(root, { recursive: true });
  await fs.mkdir('work/screenshots', { recursive: true });
  const env = { ...process.env, NOTELAH_TEST_DATA_DIR: path.join(root, 'data') };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await _electron.launch({ args: ['.'], cwd: process.cwd(), env });
  const errors = [];
  try {
    const page = await app.firstWindow();
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewportSize({ width: 1420, height: 1000 });
    await page.getByRole('button', { name: 'Notes', exact: true }).click();
    await page.getByRole('heading', { name: 'Notes.' }).waitFor();
    await page.getByRole('button', { name: 'New folder', exact: true }).click();
    await page.getByLabel('Folder name', { exact: true }).fill('Degree Project');
    await page.getByRole('dialog').getByRole('button', { name: 'Create folder', exact: true }).click();
    await page.locator('.notes-folder').filter({ hasText: 'Degree Project' }).click();
    await page.getByRole('button', { name: 'New note', exact: true }).click();
    await page.getByLabel('Title', { exact: true }).fill('Supervisor meeting');
    await page.getByLabel('Note', { exact: true }).fill('Start with notes and folders.\nThen add retrieval with sources.');
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    await page.getByText('All changes saved', { exact: true }).waitFor();
    const text = path.join(root, 'research.txt'); const md = path.join(root, 'ideas.md'); const pdf = path.join(root, 'reference.pdf');
    await fs.writeFile(text, 'Evidence from research.\n<script>window.notesUnsafe = true</script>');
    await fs.writeFile(md, '# Ideas\nA local workspace.');
    await fs.writeFile(pdf, '%PDF-1.4\n% Storage fixture\n%%EOF');
    await app.evaluate(({ dialog }, paths) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: paths }); }, [text, md, pdf]);
    await page.getByRole('button', { name: 'Import files', exact: true }).click();
    await page.locator('.note-card h3').filter({ hasText: 'reference.pdf' }).waitFor();
    assert.equal(await page.locator('.note-card').count(), 4);
    for (const file of [text, md, pdf]) await fs.unlink(file);
    await page.locator('.note-card-content').filter({ hasText: 'research.txt' }).click();
    assert.equal(await page.getByLabel('File contents').inputValue(), 'Evidence from research.\n<script>window.notesUnsafe = true</script>');
    assert.equal(await page.getByLabel('File contents').getAttribute('readonly'), '');
    assert.equal(await page.evaluate(() => window.notesUnsafe), undefined);
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await app.evaluate(({ shell }) => { shell.openPath = async file => { globalThis.notesOpenedPath = file; return ''; }; });
    await page.locator('.note-card-content').filter({ hasText: 'reference.pdf' }).click();
    await page.getByRole('button', { name: 'Open PDF', exact: true }).click();
    await page.waitForTimeout(200);
    const opened = await app.evaluate(() => globalThis.notesOpenedPath);
    assert.ok(opened.startsWith(path.join(root, 'data', 'files') + path.sep));
    assert.ok(opened.endsWith('.pdf'));
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.screenshot({ path: 'work/screenshots/notes-library.png', fullPage: true });
    await page.getByRole('button', { name: 'Delete folder Degree Project', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Delete folder', exact: true }).click();
    assert.equal(await page.locator('.note-card').count(), 4);
    await page.reload();
    await page.locator('.note-card h3').filter({ hasText: 'Supervisor meeting' }).waitFor();
    assert.equal(await page.locator('.note-card').count(), 4);
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    await page.getByText(path.join(root, 'data', 'files'), { exact: true }).waitFor();
    const backup = path.join(root, 'library.sqlite');
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, backup);
    await page.getByRole('button', { name: 'Create backup', exact: true }).click();
    await page.getByText('Backup saved.', { exact: true }).waitFor();
    assert.ok((await fs.stat(backup)).size > 0);
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, backup);
    await page.getByRole('button', { name: 'Restore', exact: true }).click();
    await page.getByText('0 tasks · 4 notes · 0 folders', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Restore workspace', exact: true }).click();
    await page.getByText('Your workspace has been restored.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Notes', exact: true }).click();
    assert.equal(await page.locator('.note-card').count(), 4);
    await page.setViewportSize({ width: 900, height: 800 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Desktop Notes QA passed: folders, written notes, TXT/MD/PDF imports, moved originals, safe previews, managed PDF opening, Inbox recovery, reload, complete backup/restore, storage location, and narrow layout. User data was isolated.');
  } finally {
    await app.close();
    assert.ok(root.startsWith(path.resolve('work') + path.sep));
    await fs.rm(root, { recursive: true, force: true });
  }
})().catch(error => { console.error(error); process.exit(1); });
